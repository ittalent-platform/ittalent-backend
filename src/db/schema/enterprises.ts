import { sqliteTable, text, integer, index, uniqueIndex } from 'drizzle-orm/sqlite-core';
import type { CompanySize, CompanyType, EnterpriseAddress, EnterpriseSocialLinks, EnterpriseStatus } from '../../models/enterprise.model.js';

export const enterprises = sqliteTable(
  'enterprises',
  {
    id: text('id', { length: 24 }).primaryKey(),
    name: text('name').notNull(),
    legal_name: text('legal_name'),
    tax_code: text('tax_code').notNull(),
    registration_number: text('registration_number'),
    founded_year: integer('founded_year'),
    email: text('email').notNull(),
    phone: text('phone').notNull(),
    website: text('website'),
    industry: text('industry').notNull(),
    sub_industries: text('sub_industries', { mode: 'json' }).$type<string[]>(),
    company_size: text('company_size').$type<CompanySize>().notNull(),
    company_type: text('company_type').$type<CompanyType>(),
    address: text('address', { mode: 'json' }).$type<EnterpriseAddress>().notNull(),
    branches: text('branches', { mode: 'json' }).$type<EnterpriseAddress[]>(),
    logo_url: text('logo_url'),
    cover_url: text('cover_url'),
    short_description: text('short_description'),
    description: text('description'),
    culture_summary: text('culture_summary'),
    benefits: text('benefits', { mode: 'json' }).$type<string[]>(),
    tech_stack: text('tech_stack', { mode: 'json' }).$type<string[]>(),
    social_links: text('social_links', { mode: 'json' }).$type<EnterpriseSocialLinks>(),
    working_days: text('working_days'),
    media_gallery: text('media_gallery', { mode: 'json' }).$type<string[]>(),
    status: text('status').$type<EnterpriseStatus>().default('pending').notNull(),
    status_reason: text('status_reason'),
    status_updated_by: text('status_updated_by', { length: 24 }),
    status_updated_at: integer('status_updated_at', { mode: 'timestamp_ms' }),
    creator_account_id: text('creator_account_id', { length: 24 }).notNull(),
    admin_mutation_version: integer('admin_mutation_version').default(0).notNull(),
    is_deleted: integer('is_deleted', { mode: 'boolean' }).default(false).notNull(),
    deleted_at: integer('deleted_at', { mode: 'timestamp_ms' }),
    deleted_by: text('deleted_by', { length: 24 }),
    createdAt: integer('created_at', { mode: 'timestamp_ms' }).$defaultFn(() => new Date()).notNull(),
    updatedAt: integer('updated_at', { mode: 'timestamp_ms' }).$defaultFn(() => new Date()).notNull(),
  },
  (table) => [
    index('enterprises_name_idx').on(table.name),
    uniqueIndex('enterprises_tax_code_idx').on(table.tax_code),
    index('enterprises_status_idx').on(table.status),
    index('enterprises_creator_idx').on(table.creator_account_id),
  ],
);

export const enterpriseRegistrations = sqliteTable(
  'enterprise_registrations',
  {
    id: text('id', { length: 24 }).primaryKey(),
    user_id: text('user_id', { length: 24 }),
    company_name: text('company_name').notNull(),
    tax_code: text('tax_code').notNull(),
    representative_name: text('representative_name').notNull(),
    representative_email: text('representative_email').notNull(),
    representative_phone: text('representative_phone').notNull(),
    company_email: text('company_email').notNull(),
    company_phone: text('company_phone').notNull(),
    website: text('website'),
    industry: text('industry').notNull(),
    company_size: text('company_size').notNull(),
    address: text('address', { mode: 'json' }).$type<EnterpriseAddress>().notNull(),
    business_license_url: text('business_license_url'),
    status: text('status', { enum: ['pending', 'approved', 'rejected'] }).default('pending').notNull(),
    rejection_reason: text('rejection_reason'),
    reviewed_by: text('reviewed_by', { length: 24 }),
    reviewed_at: integer('reviewed_at', { mode: 'timestamp_ms' }),
    created_enterprise_id: text('created_enterprise_id', { length: 24 }),
    createdAt: integer('created_at', { mode: 'timestamp_ms' }).$defaultFn(() => new Date()).notNull(),
    updatedAt: integer('updated_at', { mode: 'timestamp_ms' }).$defaultFn(() => new Date()).notNull(),
  },
  (table) => [
    index('ent_reg_status_idx').on(table.status),
    index('ent_reg_email_idx').on(table.representative_email),
  ],
);
